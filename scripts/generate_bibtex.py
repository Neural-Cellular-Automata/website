#!/usr/bin/env python3
"""Regenerate the literature's BibTeX snippets and download from its metadata.

Run after editing _data/literature.json:
    python3 scripts/generate_bibtex.py
Verify that generated citations are current without writing:
    python3 scripts/generate_bibtex.py --check
Only known metadata is exported; no page numbers, DOIs or dates are guessed.
"""

import argparse
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlparse

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "_data/literature.json"
EXPORT = ROOT / "assets/data/nca-literature.bib"


def escape(value):
    return str(value).translate(str.maketrans({
        "\\": r"\textbackslash{}", "{": r"\{", "}": r"\}",
        "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
        "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }))


def citation(paper):
    venue = paper["venue"]
    if paper["id"] in {"6RVYVQUP", "UI29T3TY"}:
        kind, venue_field = "book", "publisher"
    elif paper["id"] == "78MS4SZ9":
        kind, venue_field = "incollection", "booktitle"
    elif venue.lower().startswith("arxiv") or paper["id"] == "ABYJYDT4":
        kind, venue_field = "misc", "howpublished"
    elif "Transactions on Graphics" not in venue and re.search(
        r"ALIFE|ICLR|MICCAI|SIGGRAPH|CVPR|WACV|GECCO|IPMI|MIDL|"
        r"Neural Information Processing Systems", venue
    ):
        kind, venue_field = "inproceedings", "booktitle"
    else:
        kind, venue_field = "article", "journal"

    authors = " and ".join(
        "others" if author == "et al." else escape(author)
        for author in paper["authors"]
    )
    fields = [
        ("author", authors),
        # Protect the title's capitalisation, including NCA and model names.
        ("title", "{" + escape(paper["title"]) + "}"),
        ("year", str(paper["year"])),
        (venue_field, escape(venue)),
        ("url", paper["url"]),
    ]
    link = urlparse(paper["url"])
    if link.hostname in {"doi.org", "dx.doi.org"}:
        fields.append(("doi", unquote(link.path.lstrip("/"))))
    elif link.hostname == "arxiv.org":
        arxiv_id = re.search(r"/(?:abs|pdf)/(\d{4}\.\d{4,5})", link.path)
        if arxiv_id:
            fields.extend([("eprint", arxiv_id[1]), ("archivePrefix", "arXiv")])
    return "@" + kind + "{" + paper["id"] + ",\n" + ",\n".join(
        "  " + name + " = {" + value + "}" for name, value in fields
    ) + "\n}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    original = DATA.read_text(encoding="utf-8")
    data = json.loads(original)
    for paper in data["papers"]:
        paper["bibtex"] = citation(paper)
    updated = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    bibliography = (
        "% NCA literature bibliography (UTF-8)\n"
        "% Generated by scripts/generate_bibtex.py from _data/literature.json.\n\n"
        + "\n\n".join(paper["bibtex"] for paper in data["papers"]) + "\n"
    )
    if args.check:
        if original != updated or not EXPORT.exists() or EXPORT.read_text(encoding="utf-8") != bibliography:
            raise SystemExit("BibTeX is out of date. Run python3 scripts/generate_bibtex.py")
    else:
        DATA.write_text(updated, encoding="utf-8")
        EXPORT.parent.mkdir(parents=True, exist_ok=True)
        EXPORT.write_text(bibliography, encoding="utf-8")
    print(f"{'Verified' if args.check else 'Generated'} {len(data['papers'])} BibTeX entries.")


if __name__ == "__main__":
    main()
